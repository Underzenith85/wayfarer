import { URL, fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import path from "node:path";
import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import console from "node:console";
import openapiTS, { astToString } from "openapi-typescript";
import { format } from "prettier";
const root = new URL("../../contracts/v1/", import.meta.url);
const read = async (name) =>
  JSON.parse(await readFile(new URL(name, root), "utf8"));
const http = await read("openapi.json");
const shared = await read("schemas.json");
const live = await read("events.schema.json");
function rewrite(value, prefix) {
  if (Array.isArray(value)) return value.map((x) => rewrite(x, prefix));
  if (value && typeof value === "object")
    return Object.fromEntries(
      Object.entries(value).map(([k, v]) => {
        if (k === "$ref") {
          if (v.startsWith("./schemas.json#/$defs/"))
            return [k, "#/components/schemas/HTTP_" + v.split("/").at(-1)];
          if (v.startsWith("#/$defs/"))
            return [k, "#/components/schemas/" + prefix + v.split("/").at(-1)];
          throw new Error(`Unexpected schema reference ${v}`);
        }
        return [k, rewrite(v, prefix)];
      }),
    );
  return value;
}
const eventDocument = {
  openapi: "3.1.1",
  info: { title: "Live messages", version: "1.0.0" },
  paths: {},
  components: {
    schemas: {
      ...Object.fromEntries(
        Object.entries(shared.$defs).map(([k, v]) => [
          "HTTP_" + k,
          rewrite(v, "HTTP_"),
        ]),
      ),
      ...rewrite(live.$defs, ""),
    },
  },
};
const header =
  "/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n";
const outputs = new Map();
outputs.set(
  "contracts.generated.ts",
  header + astToString(await openapiTS(new URL("openapi.json", root))),
);
outputs.set(
  "events.generated.ts",
  header +
    astToString(await openapiTS(eventDocument)) +
    '\nexport type ClientMessage = components["schemas"]["ClientMessage"];\nexport type ServerMessage = components["schemas"]["ServerMessage"];\nexport type Scope = components["schemas"]["Scope"];\n',
);
const operations = {};
for (const [path, methods] of Object.entries(http.paths))
  for (const [method, op] of Object.entries(methods)) {
    if (!op.operationId) continue;
    const responses = Object.fromEntries(
      Object.entries(op.responses).map(([status, response]) => {
        if (response.$ref)
          response = http.components.responses[response.$ref.split("/").at(-1)];
        return [
          status,
          response.content["application/json"].schema.$ref.split("/").at(-1),
        ];
      }),
    );
    operations[op.operationId] = {
      method: method.toUpperCase(),
      path,
      requestSchema:
        op.requestBody?.content["application/json"].schema.$ref
          .split("/")
          .at(-1) ?? null,
      responses,
    };
  }
outputs.set(
  "operations.generated.ts",
  "// Generated from contracts/v1/openapi.json. Do not edit.\nexport const operations = " +
    JSON.stringify(operations) +
    " as const;\nexport type OperationId = keyof typeof operations;\n",
);
for (const [name, source] of outputs) {
  const formatted = await format(source, { parser: "typescript" });
  const path = new URL("../src/api/" + name, import.meta.url);
  if (process.argv.includes("--check")) {
    const committed = await readFile(path, "utf8").catch(() => null);
    if (committed !== formatted) {
      console.error(`Generated drift: ${name}. Run pnpm contracts:generate.`);
      process.exitCode = 1;
    }
  } else await writeFile(path, formatted);
}

const require = createRequire(import.meta.url);
const worker = await readFile(
  path.join(
    path.dirname(require.resolve("msw/package.json")),
    "lib/mockServiceWorker.js",
  ),
  "utf8",
);
const workerPath = fileURLToPath(
  new URL("../public/mockServiceWorker.js", import.meta.url),
);
if (process.argv.includes("--check")) {
  if ((await readFile(workerPath, "utf8").catch(() => null)) !== worker) {
    console.error(
      "Generated drift: mockServiceWorker.js. Run pnpm contracts:generate.",
    );
    process.exitCode = 1;
  }
} else await writeFile(workerPath, worker);
